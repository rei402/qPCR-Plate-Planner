'use strict';
const {JSDOM}=require('../node_modules/jsdom'),assert=require('node:assert/strict'),fs=require('node:fs');
let passed=0;
const check=(name,fn)=>{fn();passed++;console.log('PASS APK ADAPTER '+name);};
(async()=>{
  const messages=[],revoked=[],dom=new JSDOM('<div id="validationMessages"></div><input name="printOrientation" value="portrait" type="radio" checked>',{url:'https://appassets.androidplatform.net/assets/www/qPCR%20Plate%20Planner.html',runScripts:'outside-only'}),w=dom.window;
  const bytes=new Uint8Array(Buffer.from('\ufeff样本,孔位\r\n中文,A1','utf8'));
  w.fetch=async()=>({blob:async()=>({type:'text/csv;charset=utf-8',size:bytes.length,arrayBuffer:async()=>bytes.buffer})});
  w.eval(fs.readFileSync(__dirname+'/native-adapter.js','utf8'));
  w.print();
  const port={postMessage:text=>messages.push(JSON.parse(text)),start(){}};
  const event=new w.MessageEvent('message',{data:'qpcr-native-ready',ports:[port]});w.dispatchEvent(event);
  check('系统通道就绪前的打印请求能排队并保留纵向',()=>{assert.deepEqual(messages[0],{type:'print',orientation:'portrait'});});
  const link=w.document.createElement('a');link.href='blob:export';link.download='中文实验.csv';link.click();await new Promise(r=>setTimeout(r,0));
  check('Blob 导出完整传递中文 UTF-8、BOM、文件名及数据',()=>{const request=messages.find(m=>m.type==='save');assert.equal(request.name,'中文实验.csv');assert.deepEqual(Buffer.from(request.base64,'base64'),Buffer.from(bytes));});
  const request=messages.find(m=>m.type==='save');
  port.onmessage({data:JSON.stringify({type:'save-result',id:request.id,name:request.name,status:'cancelled'})});
  check('取消保存明确提示，不误报文件已保存',()=>{assert.match(w.document.body.textContent,/已取消文件保存/);assert.ok(!w.document.body.textContent.includes('文件已保存：'));});
  port.onmessage({data:JSON.stringify({type:'save-result',id:request.id,name:'<img src=x onerror=alert(1)>.json',status:'saved'})});
  check('保存结果名称作为纯文本呈现',()=>{assert.equal(w.document.querySelectorAll('img').length,0);assert.match(w.document.body.textContent,/文件已保存/);});
  let printed=0;w.addEventListener('afterprint',()=>printed++);port.onmessage({data:'{"type":"afterprint"}'});
  check('系统打印结束恢复原页面打印状态',()=>assert.equal(printed,1));
  const lock=await w.navigator.wakeLock.request('screen');await lock.release();await lock.release();
  check('常亮请求与释放传递系统，重复释放不会重复调用',()=>{assert.deepEqual(messages.filter(m=>m.type==='awake'),[{type:'awake',enabled:true},{type:'awake',enabled:false}]);});
  dom.window.close();
  console.log(`${passed}/${passed} APK adapter tests passed (DOM simulation)`);
})().catch(e=>{console.error(e);process.exitCode=1;});
